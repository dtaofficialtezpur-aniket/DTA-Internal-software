// Generates out/sw.js after `next build`.
// The app is a static export, so every file the app needs is in out/. We precache all of it
// (cache name is derived from the file contents, so each deploy gets a fresh cache and old ones are removed).
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const OUT = new URL('../out/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
if (!existsSync(OUT)) {
  console.error('out/ not found — run `next build` first.');
  process.exit(1);
}
const BASE = (process.env.NEXT_PUBLIC_BASE_PATH || '').replace(/\/$/, '');

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
})(OUT);

const hash = createHash('sha256');
const urls = new Set([`${BASE}/`]);
for (const f of files.sort()) {
  const rel = relative(OUT, f).split(sep).join('/');
  if (rel === 'sw.js' || rel.endsWith('.map')) continue;
  hash.update(rel).update(readFileSync(f));
  if (rel === 'index.html') urls.add(`${BASE}/`);
  else if (rel.endsWith('/index.html')) urls.add(`${BASE}/${rel.slice(0, -'index.html'.length)}`);
  else urls.add(`${BASE}/${rel}`);
}
const version = hash.digest('hex').slice(0, 12);
const precache = [...urls].sort();

const sw = `/* DTA Client Data Tracker — service worker (generated by scripts/build-sw.mjs) */
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(BASE)};
const CACHE = 'dta-tracker-' + VERSION;
const PRECACHE = ${JSON.stringify(precache)};
const OFFLINE_URL = BASE + '/offline/';

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      // one bad file must not abort the whole install
      await Promise.all(PRECACHE.map((u) => cache.add(new Request(u, { cache: 'reload' })).catch(() => {})));
    })(),
  );
  // A first install activates straight away. When an older version is running, we wait for the
  // page to ask for the update (see SKIP_WAITING below) so users aren't reloaded mid-entry.
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      const keys = await caches.keys();
      await Promise.all(keys.filter((k) => k.startsWith('dta-tracker-') && k !== CACHE).map((k) => caches.delete(k)));
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

async function refresh(request, cache) {
  try {
    const res = await fetch(request);
    if (res && res.ok) await cache.put(request, res.clone());
    return res;
  } catch {
    return undefined;
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (url.pathname === BASE + '/sw.js') return; // always let the browser check for a new worker

  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      // ignoreSearch: pages are matched without ?q=… / ?_rsc=… so every route works offline
      const cached = await cache.match(request, { ignoreSearch: true });
      const immutable = url.pathname.includes('/_next/static/');
      if (cached) {
        if (!immutable) event.waitUntil(refresh(request, cache)); // stale-while-revalidate
        return cached;
      }
      const res = await refresh(request, cache);
      if (res) return res;
      if (request.mode === 'navigate') {
        const offline = await cache.match(OFFLINE_URL);
        if (offline) return offline;
      }
      return new Response('Offline', { status: 503, statusText: 'Offline', headers: { 'Content-Type': 'text/plain' } });
    })(),
  );
});
`;
writeFileSync(join(OUT, 'sw.js'), sw);
console.log(`sw.js written — version ${version}, ${precache.length} precached URLs`);
